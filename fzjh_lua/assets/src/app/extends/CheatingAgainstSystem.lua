    local minNumber = Encryptor:encrypt(0.0001, mixNumberName)

    local keyIndex = 0
    for key, value in pairs(self.protectedValues) do
        keyIndex = keyIndex + 1
        self.protectedValues[key] = key + keyIndex
        self.contrasts[keyIndex] = Encryptor:encrypt(key, mixNumberName)
    end

    self.__coroutinePool = CoroutinePool:create()

    self.__coroutinePool:add(
        "CheatingAgainstSystem",
        function()
            while true do
                local keyIndex = 0
                local beginTime = os.clock()
                for key, value in pairs(self.protectedValues) do
                    keyIndex = keyIndex + 1
                    if math.abs(key - (value - keyIndex)) > Encryptor:decrypt(minNumber, mixNumberName) then
